/* * 辅助函数：将 ASCII 码映射到我们缩减版字库的索引
 * 字库布局：A-Z(0-25), 0-9(26-35), 小写字母占位(36-61), 空格(62)
 */
static uint8_t Get_Font_Index(char c) {
    if (c == 'c') return 0;   // 'c' 在索引0
    if (c == 's') return 1;   // 's' 在索引1
    if (c == '2') return 2;   // '2' 在索引2
    if (c == ' ') return 3;   // 空格在索引3
    if (c == 'b') return 4;   // 'b' 在索引4
    if (c == 'e') return 5;   // 'e' 在索引5
    if (c == 't') return 7;   // 't' 在索引7
    return 3; // 默认返回空格（索引3）
}

