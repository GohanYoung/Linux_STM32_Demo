#ifndef __OLED_FONT_H
#define __OLED_FONT_H

#include <stdint.h>

/* * 极简 8x16 字库 (为了测试 "cs2" 提取的片段)
 * 每个字符占用 16 个字节 (上半部分 8 字节，下半部分 8 字节)
 * 提取的字符顺序: [0]空格, [1]'2', [2]'c', [3]'s'
 */
const uint8_t F8X16[][16] = {
    // [0] ' ' (空格)
    {0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
    // [1] '2'
    {0x18,0x14,0x12,0x11,0x11,0x12,0x1C,0x00,0x07,0x06,0x05,0x04,0x04,0x04,0x04,0x00},
    // [2] 'c'
    {0x00,0x00,0x80,0x80,0x80,0x80,0x00,0x00,0x00,0x03,0x04,0x04,0x04,0x04,0x03,0x00},
    // [3] 's'
    {0x00,0x00,0x80,0x80,0x80,0x80,0x80,0x00,0x00,0x05,0x04,0x04,0x04,0x04,0x02,0x00}
};

/* * 辅助函数：将 ASCII 码映射到我们缩减版字库的索引
 * 如果使用完整的 ASCII 字库，直接用 (char - ' ') 即可
 */
static uint8_t Get_Font_Index(char c) {
    if (c == '2') return 1;
    if (c == 'c') return 2;
    if (c == 's') return 3;
    return 0; // 默认返回空格
}

#endif