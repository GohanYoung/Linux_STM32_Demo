static inline const uint8_t* font_get_bitmap(char chr) {
    for (unsigned int i = 0; i < FONT_CHAR_COUNT; i++) {
        if (font_table[i].ascii == chr) return font_table[i].bitmap;
    }
    return font_table[0].bitmap;
}

